import { generateSync } from "otplib";

// Bảng mã Base32 RFC 4648 chuẩn (A-Z, 2-7)
const BASE32_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";

/**
 * Chuyển đổi mảng byte sang chuỗi Base32 chuẩn RFC 4648
 */
export function bytesToBase32(bytes: Uint8Array): string {
  let bits = 0;
  let value = 0;
  let output = "";

  for (let i = 0; i < bytes.length; i++) {
    value = (value << 8) | bytes[i];
    bits += 8;
    while (bits >= 5) {
      output += BASE32_CHARS[(value >>> (bits - 5)) & 31];
      bits -= 5;
    }
  }
  if (bits > 0) {
    output += BASE32_CHARS[(value << (5 - bits)) & 31];
  }
  return output;
}

/**
 * Tự động nhận diện chuỗi Secret (Hex, Base64 hoặc Base32) và chuyển đổi sang Base32 chuẩn RFC 4648
 */
export function normalizeSecretToBase32(rawSecret: string): string {
  if (!rawSecret) return "";
  const clean = rawSecret.trim().replace(/\s+/g, "");

  // 1. Nếu là chuỗi Base64 (có đuôi '=' hoặc chứa ký tự đặc trưng 0, 1, 8, 9, +, /)
  if (
    /^[A-Za-z0-9+/]+={0,2}$/.test(clean) &&
    (clean.includes("=") || /[0189+/]/.test(clean))
  ) {
    try {
      const decodedString = atob(clean);
      // VNPT SmartCA lưu chuỗi text ASCII bí mật (vd: "D23195E365E9391867B2A43C97A2C8ED")
      const bytes = new Uint8Array(decodedString.length);
      for (let i = 0; i < decodedString.length; i++) {
        bytes[i] = decodedString.charCodeAt(i);
      }
      return bytesToBase32(bytes);
    } catch {}
  }

  // 2. Nếu là chuỗi Hex / ASCII 32 ký tự
  if (/^[0-9a-fA-F]{32}$/.test(clean)) {
    const bytes = new Uint8Array(clean.length);
    for (let i = 0; i < clean.length; i++) {
      bytes[i] = clean.charCodeAt(i);
    }
    return bytesToBase32(bytes);
  }

  // 3. Mặc định coi là chuỗi Base32 chuẩn RFC 4648
  return clean.toUpperCase();
}

export function getAutoGeneratedOtp(rawSecret: string): string {
  if (!rawSecret) {
    throw new Error("Chưa cung cấp SmartCA TOTP Secret Key");
  }

  const validBase32 = normalizeSecretToBase32(rawSecret);
  if (!validBase32) {
    throw new Error("Không thể chuyển đổi Secret Key sang chuẩn Base32");
  }

  return generateSync({
    secret: validBase32,
    digits: 6,
    period: 30,
  });
}
