import {
  SMARTCA_ENV,
  SMARTCA_DEFAULT_MST,
  SMARTCA_DEFAULT_CCCD,
  SMARTCA_DEFAULT_PASSWORD,
  SMARTCA_TOTP_SECRET,
  SMARTCA_USER_ID,
} from "../smartcaConfig";
import { getAutoGeneratedOtp } from "./totpHelper";
import { SmartCaThClient } from "./smartcaThClient";
import type { SmartCaSignResponse } from "../smartcaHandlers";
import {
  computeXmlDigest,
  computeSignedInfoDigest,
  extractRsaPublicKeyFromCert,
  injectSignatureToXml,
  type XmlDSigParams,
} from "../../../utils/xmlDsigEngine";
