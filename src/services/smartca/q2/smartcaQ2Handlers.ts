const CONFIG = {
  env: SMARTCA_ENV,
  defaultUsername:
    SMARTCA_USER_ID || SMARTCA_DEFAULT_MST || SMARTCA_DEFAULT_CCCD,
};

/**
 * Chuyển Base64 SHA-256 Digest sang chuỗi Hex 64 ký tự thường (nếu chưa có Hex)
 */
function base64ToHex(base64: string): string {
  try {
    const raw = atob(base64.trim());
    return Array.from(raw, (c) => c.charCodeAt(0).toString(16).padStart(2, "0"))
      .join("")
      .toLowerCase();
  } catch {
    return "";
  }
}

/**
 * Bước 1: Khởi tạo giao dịch ký số Q2 thủ công (dành cho luồng hiển thị Modal nhập OTP)
 */
export async function initiateSignQ2(
  req: SmartCaQ2InitiateRequest,
): Promise<SmartCaQ2InitiateResult> {
  try {
    if (!req.rawXml) {
      return { success: false, error: "Dữ liệu XML rỗng, không thể ký số." };
    }

    const username = (req.identityValue || CONFIG.defaultUsername || "").trim();
    const password =
      req.password !== undefined ? req.password : SMARTCA_DEFAULT_PASSWORD;

    if (!username || !password) {
      return {
        success: false,
        error:
          "Vui lòng cung cấp mã định danh (MST/CCCD) và mật khẩu tài khoản SmartCA.",
      };
    }

    // 1. Kết nối Cổng VNPT SmartCA-TH lấy chứng thư số hợp lệ
    const thClient = new SmartCaThClient({ env: CONFIG.env });
    const { userCert } = await thClient.getCertificate(username);

    const x509Certificate = (userCert.cert_data || "").trim();
    if (!x509Certificate) {
      return {
        success: false,
        error: "Không tìm thấy chứng thư số X.509 hợp lệ từ Cổng VNPT SmartCA.",
      };
    }

    const extractedRsa = extractRsaPublicKeyFromCert(x509Certificate);
    const rsaModulus = extractedRsa?.modulus || "";
    const rsaExponent = extractedRsa?.exponent || "AQAB";

    // 2. Tính toán DigestValue của XML gốc và SignedInfo Digest
    let documentDigest = req.documentDigest;
    if (!documentDigest) {
      const digestRes = await computeXmlDigest(req.rawXml, {
        preserveOtherSignatures: true,
      });
      documentDigest = digestRes.digestValue;
    }

    const signedInfoRes = await computeSignedInfoDigest(
      documentDigest,
      req.rawXml,
    );
    const signedInfoDigest = signedInfoRes.digestValue;
    const signedInfoHex = signedInfoRes.hexDigest;

    // 3. Đóng gói WaitingQ2Transaction lưu giữ đầy đủ DigestValue và chứng thư số
    const transactionId = crypto.randomUUID();
    const fileName = req.fileName || "HoSoChungTu.xml";

    const waitingTx: WaitingQ2Transaction = {
      transactionId,
      documentDigest,
      signedInfoDigest,
      signedInfoHex,
      rawXml: req.rawXml,
      fileName,
      userId: username,
      password,
      certInfo: {
        subjectDN: userCert.cert_subject || `CN=${username}`,
        serialNumber: userCert.serial_number,
        issuerDN: "",
        x509Certificate,
        rsaModulus,
        rsaExponent,
      },
      signer: req.signer,
      initiatedAt: Date.now(),
      expiresInSeconds: 180, // TTL mặc định 3 phút
    };

    return {
      success: true,
      waitingTx,
    };
  } catch (err: unknown) {
    const errorMsg =
      err instanceof Error
        ? err.message
        : "Lỗi kết nối khởi tạo giao dịch SmartCA Q2";
    console.error("Lỗi initiateSignQ2:", err);
    return {
      success: false,
      error: errorMsg,
    };
  }
}

/**
 * Bước 2: Xác thực mã OTP từ Modal (Ủy quyền ký số và nhận chữ ký số tức thì)
 */
export async function authorizeSignQ2(
  req: SmartCaQ2AuthorizeRequest,
): Promise<SmartCaQ2AuthorizeResult> {
  try {
    const cleanOtp = (req.totpCode || "").replace(/\D/g, "").trim();
    if (cleanOtp.length !== 6) {
      return {
        success: false,
        error: "Vui lòng nhập đủ 6 chữ số mã Smart OTP.",
        canRetryOtp: true,
      };
    }

    const username = (req.userId || CONFIG.defaultUsername || "").trim();
    const password =
      req.password !== undefined ? req.password : SMARTCA_DEFAULT_PASSWORD;
    const fileName = req.fileName || "HoSoChungTu.xml";
    const serialNumber = req.serialNumber || "";

    // Lấy chuỗi Hex 64 ký tự của SignedInfo
    let hashHex = req.signedInfoHex || "";
    if (!hashHex && req.signedInfoDigest) {
      hashHex = base64ToHex(req.signedInfoDigest);
    }

    if (!hashHex) {
      return {
        success: false,
        error: "Thiếu dữ liệu băm SignedInfo để thực hiện ký số.",
        canRetryOtp: false,
      };
    }

    const thClient = new SmartCaThClient({ env: CONFIG.env });

    // 1. Gửi lệnh ký sign kèm OTP để lấy chuỗi SAD
    const signRes = await thClient.signHash({
      userId: username,
      password,
      otp: cleanOtp,
      serialNumber,
      hashHex,
      fileName,
    });

    // 2. Xác nhận nhận chữ ký bằng chuỗi SAD
    const confirmRes = await thClient.confirmSign({
      userId: username,
      password,
      transactionId: signRes.transactionId,
      sad: signRes.sad,
    });

    const signatureValue = confirmRes.signatureValue;
    if (!signatureValue) {
      return {
        success: false,
        error: "Không nhận được chuỗi chữ ký số từ Cổng SmartCA-TH.",
        canRetryOtp: false,
      };
    }

    return {
      success: true,
      signatures: [signatureValue],
      signatureValue,
    };
  } catch (err: unknown) {
    const errorMsg =
      err instanceof Error
        ? err.message
        : "Không thể kết nối đến máy chủ xác thực SmartCA";

    const isWrongOtp =
      errorMsg.includes("1003") ||
      errorMsg.toLowerCase().includes("otp không chính xác") ||
      errorMsg.toLowerCase().includes("mã otp");

    const isExpired =
      errorMsg.toLowerCase().includes("hết hạn") ||
      errorMsg.toLowerCase().includes("expired") ||
      errorMsg.toLowerCase().includes("quá số lần");

    return {
      success: false,
      error: errorMsg,
      canRetryOtp: isWrongOtp && !isExpired,
      isExpired,
    };
  }
}

export function injectSignedXmlQ2(
  waitingTx: WaitingQ2Transaction,
  signatureValue: string,
): SmartCaQ2SignAndInjectResult {
  try {
    const { documentDigest, rawXml, certInfo, signer } = waitingTx;

    if (!documentDigest || !rawXml) {
      throw new Error("Dữ liệu giao dịch Q2 thiếu documentDigest hoặc rawXml.");
    }

    if (!signatureValue) {
      throw new Error(
        "Không có chuỗi chữ ký số (signatureValue) để nhúng vào XML.",
      );
    }

    const dsigParams: XmlDSigParams = {
      signatureId: `Id-${crypto.randomUUID()}`,
      digestValue: documentDigest, // TÁI SỬ DỤNG HOÀN TOÀN - KHÔNG BĂM LẠI
      signatureValue,
      subjectDN: certInfo.subjectDN,
      x509Certificate: certInfo.x509Certificate,
      rsaModulus: certInfo.rsaModulus || undefined,
      rsaExponent: certInfo.rsaExponent || "AQAB",
      signingTime: new Date().toISOString(),
    };

    const signedXml = injectSignatureToXml(rawXml, dsigParams);

    const signResponse: SmartCaSignResponse = {
      success: true,
      tranId: waitingTx.transactionId,
      tranCode: "00",
      status: 1, // SUCCESS
      signatureValue,
      subjectDN: certInfo.subjectDN,
      serialNumber: certInfo.serialNumber,
      issuerDN: certInfo.issuerDN,
      x509Certificate: certInfo.x509Certificate,
      rsaModulus: certInfo.rsaModulus,
      rsaExponent: certInfo.rsaExponent,
      signedAt: dsigParams.signingTime || new Date().toISOString(),
      digestValue: documentDigest,
      signedXml,
      signer,
    };

    return {
      success: true,
      signedXml,
      signResponse,
    };
  } catch (err: unknown) {
    const errorMsg =
      err instanceof Error ? err.message : "Lỗi đóng gói chữ ký XML Q2";
    console.error("Lỗi injectSignedXmlQ2:", err);
    return {
      success: false,
      signedXml: waitingTx.rawXml,
      signResponse: {
        success: false,
        tranId: waitingTx.transactionId,
        signatureValue: "",
        subjectDN: "",
        serialNumber: "",
        issuerDN: "",
        x509Certificate: "",
        signedAt: "",
        digestValue: waitingTx.documentDigest,
        error: errorMsg,
      },
      error: errorMsg,
    };
  }
}

export async function signAutoQ2(
  req: SmartCaQ2InitiateRequest & { totpSecret?: string },
): Promise<SmartCaQ2SignAndInjectResult> {
  const secretKey = (req.totpSecret || SMARTCA_TOTP_SECRET || "").trim();
  if (!secretKey) {
    throw new Error("Chưa có Secret Key ký số.");
  }

  if (!req.rawXml) {
    throw new Error("Dữ liệu XML rỗng, không thể ký số.");
  }

  const username = (req.identityValue || CONFIG.defaultUsername || "").trim();
  const password =
    req.password !== undefined ? req.password : SMARTCA_DEFAULT_PASSWORD;

  if (!username || !password) {
    throw new Error(
      "Vui lòng cung cấp mã định danh (MST/CCCD) và mật khẩu tài khoản SmartCA.",
    );
  }

  const fileName = req.fileName || "HoSoChungTu.xml";
  const thClient = new SmartCaThClient({ env: CONFIG.env });

  // 1. Lấy thông tin chứng thư số và số serial
  const { userCert } = await thClient.getCertificate(username);
  const x509Certificate = (userCert.cert_data || "").trim();
  if (!x509Certificate) {
    throw new Error(
      "Không tìm thấy chứng thư số X.509 hợp lệ từ Cổng VNPT SmartCA-TH.",
    );
  }

  const extractedRsa = extractRsaPublicKeyFromCert(x509Certificate);
  const rsaModulus = extractedRsa?.modulus || "";
  const rsaExponent = extractedRsa?.exponent || "AQAB";

  // 2. Tính mã băm Document Digest và SignedInfo Digest
  let documentDigest = req.documentDigest;
  if (!documentDigest) {
    const digestRes = await computeXmlDigest(req.rawXml, {
      preserveOtherSignatures: true,
    });
    documentDigest = digestRes.digestValue;
  }

  const signedInfoRes = await computeSignedInfoDigest(
    documentDigest,
    req.rawXml,
  );
  const signedInfoDigest = signedInfoRes.digestValue;
  const signedInfoHex = signedInfoRes.hexDigest;

  // 3. Tự động sinh mã Smart OTP 6 số thời gian thực (RFC 6238)
  const autoOtp = getAutoGeneratedOtp(secretKey);
  console.log(
    "%c[SmartCA-TH Q2] 🔑 Tự động sinh mã OTP:",
    "color: #2563eb; font-weight: bold; font-size: 13px;",
    autoOtp,
  );

  // 4. Gửi yêu cầu ký số dữ liệu kèm mã OTP để lấy chuỗi SAD
  const signRes = await thClient.signHash({
    userId: username,
    password,
    otp: autoOtp,
    serialNumber: userCert.serial_number,
    hashHex: signedInfoHex,
    fileName,
    abortSignal: req.abortSignal,
  });

  // 5. Xác nhận giao dịch ký số bằng chuỗi SAD để nhận chữ ký số ngay lập tức
  const confirmRes = await thClient.confirmSign({
    userId: username,
    password,
    transactionId: signRes.transactionId,
    sad: signRes.sad,
    abortSignal: req.abortSignal,
  });

  const signatureValue = confirmRes.signatureValue;
  if (!signatureValue) {
    throw new Error("Không nhận được chuỗi chữ ký số từ Cổng SmartCA-TH.");
  }

  // 6. Đóng gói WaitingQ2Transaction và nhúng Signature vào XML
  const waitingTx: WaitingQ2Transaction = {
    transactionId: signRes.transactionId,
    documentDigest,
    signedInfoDigest,
    signedInfoHex,
    rawXml: req.rawXml,
    fileName,
    userId: username,
    certInfo: {
      subjectDN: userCert.cert_subject || `CN=${username}`,
      serialNumber: userCert.serial_number,
      issuerDN: "",
      x509Certificate,
      rsaModulus,
      rsaExponent,
    },
    signer: req.signer,
    initiatedAt: Date.now(),
    expiresInSeconds: 180,
  };

  return injectSignedXmlQ2(waitingTx, signatureValue);
}
