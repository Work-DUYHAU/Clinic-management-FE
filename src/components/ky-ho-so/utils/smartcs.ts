import {
  SMARTCA_ENV,
  SMARTCA_DEFAULT_MST,
  SMARTCA_DEFAULT_CCCD,
  SMARTCA_DEFAULT_PASSWORD,
  SMARTCA_TOTP_SECRET,
  SMARTCA_USER_ID,
} from "../../../services/smartca/smartcaConfig";
import { SmartCaThClient } from "../../../services/smartca/q2/smartcaThClient";
import { getAutoGeneratedOtp } from "../../../services/smartca/q2/totpHelper";
import { sha256Full } from "../../../utils/hash";
import type { SignaturePosition, KyHoSoSignatureMeta } from "../types";

export interface SmartCsSignResponse {
  success: boolean;
  statusCode: number;
  tranId: string;
  serialNumber: string;
  issuer: string;
  signerName: string;
  signedAt: string;
  digestValue: string;
  signatureValue: string;
  bhxhCode: string;
}
export function isSmartCsSignSuccess(res: any): boolean {
  if (!res) return false;
  return (
    (res.statusCode === 200 || res.status === 200 || res.code === 200) &&
    res.success !== false &&
    Boolean(res.signatureValue || res.serialNumber)
  );
}
export async function signWithSmartCS(
  file: File,
  _positions: SignaturePosition[],
): Promise<SmartCsSignResponse> {
  // 1. Tính mã băm SHA-256 nội dung tệp thực tế
  const buffer = await file.arrayBuffer();
  const bytes = new Uint8Array(buffer);

  let binaryStr = "";
  const len = bytes.length;
  // Băm toàn bộ nội dung tệp tài liệu để đảm bảo toàn vẹn dữ liệu
  const chunkSize = 8192;
  for (let i = 0; i < len; i += chunkSize) {
    const chunk = bytes.subarray(i, i + chunkSize);
    binaryStr += String.fromCharCode.apply(null, chunk as unknown as number[]);
  }

  const hashResult = await sha256Full(binaryStr || file.name);
  const hashHex = hashResult.hex.toLowerCase();

  // 2. Lấy cấu hình tài khoản SmartCA Q2 từ môi trường (.env hoặc localStorage)
  const userId = (
    localStorage.getItem("smartca_q2_user_id") ||
    SMARTCA_USER_ID ||
    SMARTCA_DEFAULT_MST ||
    SMARTCA_DEFAULT_CCCD ||
    ""
  ).trim();

  const password = (
    localStorage.getItem("smartca_q2_password") ||
    SMARTCA_DEFAULT_PASSWORD ||
    ""
  ).trim();

  const secretKey = (
    localStorage.getItem("smartca_q2_totp_secret") ||
    SMARTCA_TOTP_SECRET ||
    ""
  ).trim();

  if (!userId || !password) {
    throw new Error(
      "Chưa cấu hình tài khoản ký số VNPT SmartCA (VITE_SMARTCA_USER_ID và VITE_SMARTCA_PASSWORD). Vui lòng kiểm tra tệp .env",
    );
  }

  if (!secretKey) {
    throw new Error(
      "Chưa cấu hình khóa bí mật SmartCA TOTP Secret (VITE_SMARTCA_TOTP_SECRET) để ký tự động theo Quy trình Q2.",
    );
  }

  const thClient = new SmartCaThClient({ env: SMARTCA_ENV });

  // 3. Lấy chứng thư số và số serial thực tế của thuê bao từ Cổng VNPT SmartCA-TH
  const { userCert } = await thClient.getCertificate(userId);
  if (!userCert || !userCert.serial_number) {
    throw new Error(
      `Không tìm thấy chứng thư số hợp lệ của thuê bao SmartCA (${userId}).`,
    );
  }

  // 4. Tự động sinh mã Smart OTP 6 số theo thời gian thực (RFC 6238 TOTP)
  const autoOtp = getAutoGeneratedOtp(secretKey);

  // 5. Gửi yêu cầu ký mã băm tệp lên cổng VNPT để lấy chuỗi SAD
  const signRes = await thClient.signHash({
    userId,
    password,
    otp: autoOtp,
    serialNumber: userCert.serial_number,
    hashHex,
    fileName: file.name,
  });

  if (!signRes.sad || !signRes.transactionId) {
    throw new Error("Không nhận được chuỗi xác thực SAD từ Cổng VNPT SmartCA.");
  }

  // 6. Xác nhận giao dịch để nhận chuỗi chữ ký số RSA thực tế từ Cổng VNPT
  const confirmRes = await thClient.confirmSign({
    userId,
    password,
    transactionId: signRes.transactionId,
    sad: signRes.sad,
  });

  const signatureValue = confirmRes.signatureValue;
  if (!signatureValue) {
    throw new Error(
      "Cổng VNPT SmartCA không trả về chuỗi chữ ký số cho giao dịch này.",
    );
  }

  // 7. Định dạng ngày giờ và chuẩn bị phản hồi
  const now = new Date();
  const dateFormatted = now.toLocaleDateString("vi-VN", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  });
  const timeFormatted = now.toLocaleTimeString("vi-VN", {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });

  const ymd = now.toISOString().slice(0, 10).replace(/-/g, "");
  const randomSuffix = Math.floor(1000 + Math.random() * 9000);

  // Trích xuất tên người ký sạch từ subjectDN (vd: "CN=PHÒNG KHÁM ĐA KHOA OURMED TAM KỲ")
  const cnMatch = userCert.cert_subject?.match(/CN=([^,]+)/i);
  const signerName = cnMatch
    ? cnMatch[1].trim()
    : userCert.cert_subject || userId;

  return {
    success: true,
    statusCode: 200,
    tranId: signRes.transactionId,
    serialNumber: userCert.serial_number,
    issuer: userCert.service_name || "VNPT-CA",
    signerName,
    signedAt: `${dateFormatted} ${timeFormatted}`,
    digestValue: hashResult.base64,
    signatureValue,
    bhxhCode: `BH-${userId}-${ymd}-${randomSuffix}`,
  };
}

/**
 * Chuyển đổi SmartCsSignResponse sang KyHoSoSignatureMeta
 */
export function toSignatureMeta(res: SmartCsSignResponse): KyHoSoSignatureMeta {
  return {
    signerName: res.signerName,
    signTime: res.signedAt,
    certSerial: res.serialNumber,
    caProvider: res.issuer,
    bhxhCode: res.bhxhCode,
    signatureValue: res.signatureValue,
    isXmlSigned: true,
  };
}
